// The icon an account shows when it has none of its own, by account type.
export const ACCOUNT_TYPE_ICONS = { current: 'bank', savings: 'safe', credit_card: 'card', cash_wallet: 'wallet', investment: 'chart' };

/** A readable name for an icon ID: 'fork-knife' → 'fork knife'. */
export function pixelIconLabel(id) {
  return id.replace(/-/g, ' ');
}

/** One rectangle per horizontal run of ink: [x, y, width]. */
export function pixelIconRuns(id, icons = PIXEL_ICONS) {
  const rows = Object.hasOwn(icons, id) ? icons[id] : [];
  const runs = [];
  rows.forEach((row, y) => {
    for (const match of row.matchAll(/#+/g)) runs.push([match.index, y, match[0].length]);
  });
  return runs;
}

/** The icon as SVG markup, or '' for an unknown ID. */
export function pixelIconSvg(id) {
  const runs = pixelIconRuns(id);
  if (!runs.length) return '';
  const rects = runs.map(([x, y, width]) => `<rect x="${x}" y="${y}" width="${width}" height="1"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" class="cat-icon cat-icon--pixel" viewBox="0 0 ${PIXEL_ICON_SIZE} ${PIXEL_ICON_SIZE}" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true" focusable="false">${rects}</svg>`;
}

/** The icon as an SVG element, or null for an unknown ID. */
export function pixelIconNode(id, icons = PIXEL_ICONS, className = 'cat-icon cat-icon--pixel') {
  const runs = pixelIconRuns(id, icons);
  if (!runs.length) return null;
  const namespace = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(namespace, 'svg');
  const attributes = {
    class: className,
    viewBox: `0 0 ${PIXEL_ICON_SIZE} ${PIXEL_ICON_SIZE}`,
    'shape-rendering': 'crispEdges',
    fill: 'currentColor',
    'aria-hidden': 'true',
    focusable: 'false'
  };
  for (const [name, value] of Object.entries(attributes)) svg.setAttribute(name, value);
  for (const [x, y, width] of runs) {
    const rect = document.createElementNS(namespace, 'rect');
    rect.setAttribute('x', x);
    rect.setAttribute('y', y);
    rect.setAttribute('width', width);
    rect.setAttribute('height', 1);
    svg.append(rect);
  }
  return svg;
}

/** The icon for a navigation tab, or null for an unknown tab. */
export function navIconNode(id) {
  return pixelIconNode(id, NAV_ICONS, 'tab-icon');
}

/**
 * The element for a category's icon, or null when it has none.
 * Emoji are text; pixel icons are SVG. Both are decorative: the name follows.
 */
export function categoryIconNode(icon) {
  if (!icon) return null;
  if (icon.type === 'pixel') return pixelIconNode(icon.value);
  if (icon.type !== 'emoji' || !icon.value) return null;
  const span = document.createElement('span');
  span.className = 'cat-icon cat-icon--emoji';
  span.setAttribute('aria-hidden', 'true');
  span.textContent = icon.value;
  return span;
}

/** The first grapheme of what was typed, so an emoji field holds one symbol. */
export function firstGrapheme(text) {
  const trimmed = String(text).trim();
  if (!trimmed) return '';
  if (typeof Intl !== 'undefined' && Intl.Segmenter) {
    for (const part of new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(trimmed)) return part.segment;
  }
  return [...trimmed][0];
}

/** An account's icon: its own if it has one, otherwise the drawing for its type. */
export function accountIconNode(account) {
  return categoryIconNode(account.icon) || pixelIconNode(ACCOUNT_TYPE_ICONS[account.type] || 'bank');
}
